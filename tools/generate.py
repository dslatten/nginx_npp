#!/usr/bin/env python3
"""Build both Notepad++ UDLs from the shared vocabulary, lexer, and palettes."""

import argparse
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
GROUPS = (
    "variable_prefixes", "named_location_prefixes", "structural",
    "directives", "legacy", "parameters",
)


def read_json(root, name):
    return json.loads((root / "src" / name).read_text(encoding="utf-8"))


def keyword_groups(vocabulary):
    if set(vocabulary) != set(GROUPS):
        raise ValueError("keywords.json must contain exactly: " + ", ".join(GROUPS))
    seen = set()
    for name, words in vocabulary.items():
        if not isinstance(words, list) or any(
            not isinstance(word, str) or not word or re.search(r"\s", word)
            for word in words
        ):
            raise ValueError(f"{name}: expected a list of nonempty single tokens")
        if words != sorted(set(words)):
            raise ValueError(f"{name}: tokens must be sorted and unique")
        overlap = seen.intersection(words)
        if overlap:
            raise ValueError(f"{name}: tokens occur in multiple groups: {sorted(overlap)}")
        seen.update(words)
    result = [
        vocabulary["variable_prefixes"], vocabulary["named_location_prefixes"],
        vocabulary["structural"], sorted(vocabulary["directives"] + vocabulary["legacy"]),
        vocabulary["parameters"], [], [], [],
    ]
    # Keep well below the UDL keyword editor's 30,000-character limit.
    for number, words in enumerate(result, 1):
        if len(" ".join(words)) >= 30000:
            raise ValueError(f"Keywords{number} exceeds the UDL editor limit")
    return result


def make_udl(groups, lexer, theme, version):
    root = ET.Element("NotepadPlus")
    root.append(ET.Comment(
        f" Generated by tools/generate.py; Nginx {version}. Edit src files, then regenerate. "
    ))
    lang = ET.SubElement(root, "UserLang", name=theme["name"], ext="conf", udlVersion="2.1")
    settings = ET.SubElement(lang, "Settings")
    ET.SubElement(settings, "Global", caseIgnored="no" if lexer["case_sensitive"] else "yes",
                  allowFoldOfComments="no", foldCompact="no", forcePureLC="0",
                  decimalSeparator="0")
    ET.SubElement(settings, "Prefix", **{
        f"Keywords{i}": "yes" if i in (1, 2) else "no" for i in range(1, 9)
    })
    lists = ET.SubElement(lang, "KeywordLists")

    def keywords(name, value=""):
        ET.SubElement(lists, "Keywords", name=name).text = value

    keywords("Comments", f"00{lexer['line_comment']} 01 02 03 04")
    for name in ("prefix1", "prefix2", "extras1", "extras2", "suffix1", "suffix2", "range"):
        keywords("Numbers, " + name, " ".join(lexer["number_suffixes"]) if name == "suffix1" else "")
    keywords("Operators1", " ".join(lexer["operators"]))
    keywords("Operators2")
    for group in ("code1", "code2", "comment"):
        for part in ("open", "middle", "close"):
            value = lexer.get("fold_" + part, "") if group == "code1" else ""
            keywords(f"Folders in {group}, {part}", value)
    for number, words in enumerate(groups, 1):
        keywords(f"Keywords{number}", " ".join(words))
    delimiters = lexer["delimiters"]
    if len(delimiters) > 8:
        raise ValueError("UDL supports at most eight delimiter pairs")
    fields = []
    for number in range(8):
        spec = delimiters[number] if number < len(delimiters) else {}
        for offset, part in enumerate(("open", "escape", "close")):
            fields.append(f"{number * 3 + offset:02d}{spec.get(part, '')}")
    keywords("Delimiters", " ".join(fields))
    styles = ET.SubElement(lang, "Styles")

    def style(name, role="default", font=0, nesting=0):
        color = theme["colors"][role]
        if not re.fullmatch(r"[0-9A-F]{6}", color):
            raise ValueError(f"Invalid color for {role}: {color}")
        # Apply foregrounds; inherit the active editor background for spaces and text alike.
        ET.SubElement(styles, "WordsStyle", name=name, fgColor=color,
                      bgColor=theme["background"], colorStyle="1", fontName="",
                      fontStyle=str(font), nesting=str(nesting))

    style("DEFAULT")
    style("COMMENTS", "comment", 2)
    style("LINE COMMENTS", "comment", 2)
    style("NUMBERS", "number")
    roles = ("variable", "named_location", "structure", "directive", "parameter",
             "default", "default", "default")
    for number, role in enumerate(roles, 1):
        style(f"KEYWORDS{number}", role, 1 if number in (2, 3) else 0)
    style("OPERATORS", "operator")
    for name in ("FOLDER IN CODE1", "FOLDER IN CODE2", "FOLDER IN COMMENT"):
        style(name, "structure", 1)
    for number in range(8):
        spec = delimiters[number] if number < len(delimiters) else {}
        style(f"DELIMITERS{number + 1}", spec.get("style", "default"),
              nesting=spec.get("nesting", 0))
    ET.indent(root, space="    ")
    return ET.tostring(root, encoding="utf-8", xml_declaration=True, short_empty_elements=False) + b"\n"


def build_outputs(root=ROOT):
    groups = keyword_groups(read_json(root, "keywords.json"))
    lexer = read_json(root, "lexer.json")
    themes = read_json(root, "themes.json")
    version = read_json(root, "sources.json")["nginx"]["version"]
    outputs = {}
    for theme in themes.values():
        filename = theme["filename"]
        if Path(filename).name != filename or not filename.endswith(".xml") or filename in outputs:
            raise ValueError(f"Invalid or duplicate output filename: {filename}")
        outputs[filename] = make_udl(groups, lexer, theme, version)
    descriptions = (
        "Variable and FastCGI/SCGI parameter prefixes (prefix matching).",
        "Named location prefix (prefix matching).",
        "Structural directives and include (exact matching).",
        "Current and retained legacy directive names (exact matching).",
        "Common parameter values (exact matching).",
    )
    for number, description in enumerate(descriptions, 1):
        words = groups[number - 1]
        text = (f"Words{number}\n{'=' * 6}\n\n{description}\n\n"
                "Generated by tools/generate.py from src/keywords.json.\n"
                "Edit that JSON source and regenerate both XML themes.\n"
                "Editing this reference file alone does not change highlighting.\n\n"
                "Space-separated:\n" + " ".join(words) + "\n\n"
                "One per line:\n" + "\n".join(words) + "\n")
        outputs[f"src/Words{number}.txt"] = text.encode("utf-8")
    return outputs


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report stale outputs without changing files")
    args = parser.parse_args(argv)
    try:
        outputs = build_outputs()
    except (ValueError, KeyError, OSError) as error:
        parser.exit(2, f"Generation failed: {error}\n")
    stale = []
    for name, expected in outputs.items():
        path = ROOT / name
        if not path.exists() or path.read_bytes() != expected:
            stale.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(expected)
    if args.check and stale:
        print("Generated files are stale; run python tools/generate.py:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
